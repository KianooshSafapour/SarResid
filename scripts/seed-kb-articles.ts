async function main() {
  const all = [...ARTICLES_1, ...ARTICLES_2]
  let filled = 0
  let created = 0
  let skipped = 0

  for (const a of all) {
    const existing = await db.kbArticle.findUnique({ where: { slug: a.slug } })
    if (existing) {
      if ((existing.body ?? '').trim().length > 0 && !FORCE) {
        skipped++
        console.log(`↷ حفظ شد (body پر — ویرایش دستی): ${a.title}`)
        continue
      }
      await db.kbArticle.update({
        where: { id: existing.id },
        data: {
          title: a.title,
          category: a.category,
          summary: a.summary,
          body: a.body,
          pinned: a.pinned ?? existing.pinned,
        },
      })
      filled++
      console.log(`✓ پر شد (${wordCount(a.body)} واژه): ${a.title}`)
    } else {
      await db.kbArticle.create({
        data: {
          slug: a.slug,
          title: a.title,
          category: a.category,
          summary: a.summary,
          body: a.body,
          pinned: a.pinned ?? false,
        },
      })
      created++
      console.log(`+ ساخته شد (${wordCount(a.body)} واژه): ${a.title}`)
    }
  }

  const total = await db.kbArticle.count()
  const withBody = await db.kbArticle.count({ where: { body: { not: '' } } })
  console.log('──────────────────────────────')
  console.log(`نتیجه: ${filled} مقاله پر شد · ${created} مقالهٔ جدید · ${skipped} حفظ شد`)
  console.log(`کل مقالات دانش‌نامه: ${total} (با متن: ${withBody})`)

  // هشدار برای مقاله‌های بدون متن که در این فهرست نبودند
  const empties = await db.kbArticle.findMany({ where: { body: '' }, select: { title: true } })
  if (empties.length) {
    console.log(`⚠ مقاله‌های همچنان بدون متن: ${empties.map((e) => e.title).join('، ')}`)
  }
}

function wordCount(s: string): number {
  return s.split(/\s+/).filter(Boolean).length
}

