/* deterministic pseudo-random from index (no runtime randomness) */
function stockFor(i: number, sellPrice: number): number {
  if (sellPrice >= 400000) return 2 + ((i * 31 + 7) % 12) // کالای گران — موجودی کم
  return 3 + ((i * 7919 + 13) % 160)
}
function barcodeFor(i: number): string {
  const body = `626${String(100000 + i * 7).padStart(9, '0')}`
  let sum = 0
  for (let k = 0; k < body.length; k++) sum += Number(body[k]) * (k % 2 === 0 ? 1 : 3)
  return body + String((10 - (sum % 10)) % 10)
}
function productItem(i: number) {
  const [name, unit, category, buyPrice, sellPrice, sup] = CATALOG[i]
  return {
    holooCode: `HZ-${1001 + i}`,
    name,
    unit,
    category,
    buyPrice,
    sellPrice,
    stock: stockFor(i, sellPrice),
    supplierName: SUPPLIERS[sup].name,
    barcode: barcodeFor(i),
  }
}

/* ───────────────────────── HTTP plumbing ───────────────────────── */

function send(res: import('node:http').ServerResponse, status: number, data: unknown) {
  const body = JSON.stringify(data)
  res.writeHead(status, {
    'Content-Type': 'application/json; charset=utf-8',
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type, Authorization',
  })
  res.end(body)
}

function readBody(req: import('node:http').IncomingMessage): Promise<string> {
  return new Promise((resolve, reject) => {
    let raw = ''
    let over = false
    req.on('data', (chunk: Buffer) => {
      raw += chunk.toString('utf-8')
      if (raw.length > 1_000_000) { over = true; req.destroy() }
    })
    req.on('end', () => (over ? reject(new Error('body too large')) : resolve(raw)))
    req.on('error', reject)
  })
}

/** proxy to Holoo Apex upstream (live mode) — wraps failures as 502 { ok:false, error } */
async function proxy(upstreamPath: string): Promise<{ status: number; data: unknown }> {
  try {
    const r = await fetch(UPSTREAM + upstreamPath, {
      headers: { Authorization: `Bearer ${TOKEN}`, 'Content-Type': 'application/json' },
      signal: AbortSignal.timeout(15000),
    })
    const text = await r.text()
    let data: unknown
    try { data = JSON.parse(text) } catch { data = { raw: text.slice(0, 2000) } }
    return { status: r.ok ? 200 : 502, data: r.ok ? data : { ok: false, error: `upstream ${r.status}`, detail: data } }
  } catch (e: any) {
    return { status: 502, data: { ok: false, error: `خطای اتصال به هلو آپکس: ${e?.message || e}` } }
  }
}

const server = createServer(async (req, res) => {
  const t0 = Date.now()
  const url = new URL(req.url || '/', `http://localhost:${PORT}`)
  const path = url.pathname
  let status = 404

  try {
    // CORS preflight
    if (req.method === 'OPTIONS') {
      res.writeHead(204, {
        'Access-Control-Allow-Origin': '*',
        'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
        'Access-Control-Allow-Headers': 'Content-Type, Authorization',
      })
      res.end()
      return
    }

    /* GET /health — always local (never proxied) */
    if (req.method === 'GET' && path === '/health') {
      status = 200
      send(res, status, {
        ok: true,
        mode: MODE,
        upstream: UPSTREAM || null,
        version: VERSION,
        uptime: Math.round((Date.now() - STARTED_AT) / 1000),
        catalogSize: CATALOG.length,
        suppliers: SUPPLIERS.length,
        now: new Date().toISOString(),
      })
    }

    /* POST /api/verify { token } → { ok } */
    else if (req.method === 'POST' && path === '/api/verify') {
      const body = JSON.parse((await readBody(req)) || '{}') as { token?: string }
      if (MODE === 'live') {
        const p = await proxy('/Api/VerifyToken')
        status = p.status
        send(res, status, p.status === 200 ? { ok: true, mode: MODE } : p.data)
      } else {
        status = 200
        send(res, status, { ok: body.token === TOKEN, mode: MODE })
      }
    }

    /* GET /api/products?cursor=0&limit=100 → { items, nextCursor, total } */
    else if (req.method === 'GET' && path === '/api/products') {
      if (MODE === 'live') {
        const p = await proxy(`/Api/Products?cursor=${encodeURIComponent(url.searchParams.get('cursor') || '0')}&limit=${encodeURIComponent(url.searchParams.get('limit') || '100')}`)
        status = p.status
        send(res, status, p.data)
      } else {
        const limit = Math.min(Math.max(Number(url.searchParams.get('limit')) || 100, 1), 500)
        const cursor = Math.max(Number(url.searchParams.get('cursor')) || 0, 0)
        const total = CATALOG.length
        const items: ReturnType<typeof productItem>[] = []
        for (let i = cursor; i < Math.min(cursor + limit, total); i++) items.push(productItem(i))
        const next = cursor + limit < total ? cursor + limit : null
        status = 200
        send(res, status, { items, nextCursor: next, total, mode: MODE })
      }
    }

    /* GET /api/suppliers → { items: [...], total } */
    else if (req.method === 'GET' && path === '/api/suppliers') {
      if (MODE === 'live') {
        const p = await proxy('/Api/Suppliers')
        status = p.status
        send(res, status, p.data)
      } else {
        status = 200
        send(res, status, { items: SUPPLIERS.map((s) => ({ ...s })), total: SUPPLIERS.length, mode: MODE })
      }
    } else {
      status = 404
      send(res, status, { ok: false, error: `مسیر ناشناخته: ${req.method} ${path}` })
    }
  } catch (e: any) {
    status = 500
    try { send(res, 500, { ok: false, error: `خطای داخلی پل: ${e?.message || e}` }) } catch { /* socket gone */ }
  }

  console.log(`[holoo-bridge] ${req.method} ${path} → ${status} (${Date.now() - t0}ms) mode=${MODE}`)
})

server.listen(PORT, () => {
  console.log(`[holoo-bridge] Holoo Apex bridge v${VERSION} on :${PORT} — mode=${MODE}${UPSTREAM ? ` upstream=${UPSTREAM}` : ' (deterministic simulator)'}`)
})

process.on('SIGTERM', () => { server.close(() => process.exit(0)) })
process.on('SIGINT', () => { server.close(() => process.exit(0)) })
process.on('uncaughtException', (e) => console.error('[holoo-bridge] uncaught:', e))
process.on('unhandledRejection', (e) => console.error('[holoo-bridge] unhandled rejection:', e))
