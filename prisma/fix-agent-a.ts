async function main() {
  // 1) weekly checklist phase "" (= null in API)
  const weekly = await db.checklistTemplate.findUnique({ where: { id: 'cmv934x84002pla3wp6c65byc' } })
  if (weekly) {
    await db.checklistTemplate.update({ where: { id: weekly.id }, data: { phase: '' } })
    console.log('checklist phase fixed:', weekly.title)
  }

  // 2) SOP steps backfill
  for (const [sopId, def] of Object.entries(SOP_STEPS)) {
    const sop = await db.sop.findUnique({ where: { id: sopId } })
    if (!sop) {
      console.log('skip (missing):', sopId)
      continue
    }
    if (sop.stepsJson === '[]') {
      await db.sop.update({ where: { id: sopId }, data: { stepsJson: JSON.stringify(def.steps) } })
      console.log('steps backfilled:', sop.title, def.steps.length)
    } else {
      console.log('steps already present:', sop.title)
    }
    const key = `sop:rolekeys:${sopId}`
    await db.setting.upsert({
      where: { key },
      create: { key, value: JSON.stringify(def.roleKeys) },
      update: { value: JSON.stringify(def.roleKeys) },
    })
  }

  // 3) KB bodies backfill
  for (const [slug, body] of Object.entries(KB_BODIES)) {
    const art = await db.kbArticle.findUnique({ where: { slug } })
    if (!art) {
      console.log('kb skip (missing):', slug)
      continue
    }
    if (!art.body || art.body.trim().length === 0) {
      await db.kbArticle.update({ where: { id: art.id }, data: { body } })
      console.log('kb body backfilled:', slug, body.length, 'chars')
    } else {
      console.log('kb body already present:', slug)
    }
  }

  console.log('✅ fix-agent-a complete')
}

main()
  .catch((e) => {
    console.error(e)
    process.exit(1)
  })
  .finally(() => db.$disconnect())
